def match_style_tags(style: str) -> List[str]:
    """从风格描述中抽取匹配家具库的标签（按关键词命中）。"""
    order = ["北欧", "中式", "工业", "日式", "田园", "极简", "现代"]
    for keyword in order:
        if keyword in style:
            return list(STYLE_PROFILES[keyword]["tags"])
    return ["现代", "简约"]


